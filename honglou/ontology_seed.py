def imagery():
    return [dict(name=r[0], category=r[1], emotion=r[2], context=r[3])
            for r in _rows(IMAGERY)]


def allusions():
    return [dict(name=r[0], source=r[1], usage=r[2], person=r[3], gloss=r[4])
            for r in _rows(ALLUSIONS)]


def poet_styles():
    out = []
    for r in _rows(POET_STYLE):
        r = (r + [''] * 5)[:5]
        out.append(dict(person=r[0], style=r[1], images=[x for x in r[2].split('、') if x],
                        voice=r[3], taboo=r[4]))
    return out


def _rows(text: str):
    for line in text.strip().split('\n'):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        yield [c.strip() for c in line.split('|')]


def persons():
    out = []
    for r in _rows(PERSONS):
        r = (r + [''] * 9)[:9]
        out.append(dict(name=r[0], gender=r[1], role=r[2], residence=r[3],
                        qingbang=r[4], fate=r[5], traits=[t for t in r[6].split(',') if t],
                        aliases=[a for a in r[7].split(',') if a and a != '—'],
                        registry=r[8]))
    return out


def places():
    return [dict(name=r[0], category=r[1], belongs=r[2], note=r[3])
            for r in _rows(PLACES)]


def objects():
    return [dict(name=r[0], owner=r[1], category=r[2], symbol=r[3])
            for r in _rows(OBJECTS)]


def concepts():
    return [dict(name=r[0], category=r[1], gloss=r[2]) for r in _rows(CONCEPTS)]


def relations():
    out = []
    for r in _rows(RELATIONS):
        for b in r[2].split(','):
            b = b.strip()
            if b:
                out.append(dict(source=r[0], rel=r[1], target=b))
    return out


def clubs():
    return [dict(name=r[0], place=r[1], founder=r[2], officers=r[3], theme=r[4])
            for r in _rows(POETRY_CLUBS)]


def registry():
    return {r[0]: [x.strip() for x in r[1].split(',')] for r in _rows(REGISTRY)}


def families():
    return [dict(name=r[0], origin=r[1], seat=r[2], note=r[3]) for r in _rows(FAMILIES)]


def festivals():
    return [dict(chapter=r[0], solar_term=r[1], event=r[2]) for r in _rows(FESTIVALS)]


def lost_clues():
    return [dict(clue=r[0], source=r[1], meaning=r[2]) for r in _rows(LOST_CHAPTER_CLUES)]


